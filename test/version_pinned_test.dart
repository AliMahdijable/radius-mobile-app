import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// رقم النسخة يتبع المتجر لا الجلسة.
///
/// 🚨 انحراف 2026-08-31: رفعتُ الرقم مع كلّ بناء تجريبيّ حتّى بلغ
/// 4.6.0+186، بينما المنشور على Play/App Store عند **129**. فصار عندنا
/// مساران متوازيان: واحد في المستودع وآخر في المتجر.
///
/// والضرر ليس تجميليّاً: `versionCode` يجب أن يزيد بواحد عن المنشور
/// لا أن يقفز عشرات. والقفز يحرق أرقاماً لا يمكن استرجاعها أبداً —
/// Play يرفض أيّ رفع برقم أقلّ ممّا سبق، إلى الأبد.
///
/// القاعدة: البناء التجريبيّ **لا يرفع الرقم**. الرقم يتغيّر مرّة
/// واحدة عند النشر، بواحد فوق المتجر.
void main() {
  test('النسخة مثبَّتة على ما يلي المتجر', () {
    final raw = File('pubspec.yaml').readAsLinesSync();
    final line = raw.firstWhere((l) => l.startsWith('version:'));
    final v = line.split(':')[1].trim();
    final m = RegExp(r'^(\d+)\.(\d+)\.(\d+)\+(\d+)$').firstMatch(v);
    expect(m, isNotNull, reason: 'صيغة غير متوقّعة: $v');

    final major = int.parse(m!.group(1)!);
    final minor = int.parse(m.group(2)!);
    final patch = int.parse(m.group(3)!);
    final build = int.parse(m.group(4)!);

    // ⚠️ الحدّ الأعلى مقصود: من يبني تجريبيّاً ويرفع الرقم يصطدم بهذا
    // السطر قبل أن يحرق أرقاماً لا تُستعاد.
    // رُفع السقف ١٤٠ ← … ← ١٤٥. و٢.٢.٥ رفضه المتجر: «الإصدار مغلق
    // لرفعاتٍ جديدة» — فالمنشور فعلاً ٢.٢.٥، ولا يكفي رفع رقم البناء
    // وحده، بل يجب رفع رقم الإصدار نفسه.
    // (١٤١ رُفع للمتجر فعلاً، فلا يقبله مكرّراً).
    // عند تجهيز نسخة النشر. القاعدة لم تتغيّر: السقف يرتفع **مع**
    // النشر لا مع البناء التجريبيّ، ورفعه يبقى تعديلاً واعياً يُرى
    // في المراجعة لا أثراً جانبيّاً لبناءٍ عابر.
    // ١٤٨ (٢٠٢٦-٠٩-٢٢): ١٤٧ رُفعت فعلاً إلى App Store Connect ثمّ تبيّن
    // أنّها تحمل عطلين — أدنى iOS ١٧ بدل ١٥، و`resetOnError` منقلباً.
    // فلا يمكن إصلاحها في مكانها ولا إعادة استعمال رقمها، والسقف يرتفع
    // إلى ١٤٩: ١٤٦ و١٤٧ محروقتان، و١٤٨ وُحِّدت مع ١٤٩ لتتطابق المنصّتان.
    // 🚨 ١٥٣ و**٢.٢.٨** (٢٠٢٦-١٠-٠٦): رفضت أبل ٢.٢.٧+١٥٢ بـ
    // «Invalid Pre-Release Train: the train version '2.2.7' is closed
    // for new build submissions» — فـ٢.٢.٧ موافَقٌ عليها سلفاً.
    //
    // ⚠️ **الدرس نفسه الذي كُتب لـ٢.٢.٥ ووقعنا فيه ثانيةً:** لا يكفي
    // رفع رقم البناء على إصدارٍ أُغلق، بل يُرفع **رقم الإصدار** معه.
    // ورقم البناء تجاوز ١٥٢ لأنّ أبل قد تكون استهلكته في المعالجة،
    // وPlay قد يكون قَبِله — وحرقُ رقمٍ واحد أرخص من رفضةٍ ثانية.
    //
    // ١٥٢ (٢٠٢٦-١٠-٠٥): ١٥١ بُنيت ولم تُرفع — ثمّ لحقها إصلاح الاتصال
    // بالرقم المحلّي، فنسخةُ النشر تحمله ورقمُها يتجاوزها.
    // ١٥١ (٢٠٢٦-١٠-٠٤): ١٥٠ احترقت قبل الرفع، فالرقم يتجاوزها.
    // ١٥٠ (٢٠٢٦-١٠-٠٤): نسخة نشرٍ تحمل ميزة «تسوية الحساب» كاملةً،
    // وإصلاحات صلاحيّات، وتصغير الحزمة ٢٠٪. ١٤٩ منشورةٌ على المتجرين،
    // فالرقم يرتفع بواحدٍ فوقها. والإصدار ٢.٢.٧ لا ٢.٢.٦: المتجر لا
    // يقبل رفع رقم البناء وحده على إصدارٍ أُغلق (دُرِس في ٢.٢.٥).
    //
    // 🚀 **٣.٠.٠+١٥٤** (٢٠٢٦-١٠-١٤): MyServices Pro يحلّ محلّ الكلاسيك على
    // معرّف الحزمة نفسه (com.mysvcs.radMysvcs). آخر موافَقٍ عليه ٢.٢.٧،
    // وآخر مرفوعٍ ٢.٢.٨+١٥٣ — فالإصدار يرتفع (قطارٌ جديد ٣.٠.٠ لا يُغلقه
    // ما سبقه) **ورقم البناء** يرتفع بواحدٍ فوق ١٥٣. الدرس ذاته محفوظ في
    // الفحصين أدناه: لا إصدارَ ≤ ٢.٢.٨ (قطاران مغلقان/مستهلكان)، ولا بناءَ
    // ≤ ١٥٣ (أرقامٌ رُفعت فعلاً) — ولا قفزَ فوق ١٥٤ ببناءٍ تجريبيّ.
    //
    // **٣.٠.٠+١٥٥** (٢٠٢٦-١٠-١٤): ١٥٤ رُفعت فعلاً إلى App Store Connect، ثمّ طلب المستخدم
    // قبل الإرسال: خانة «الأجهزة» تبقى (مقفلة) بدل الإخفاء، و«دخول كموظف» تحت أزرار
    // الدخول. القطار ٣.٠.٠ ما زال مفتوحاً (لم يُرسَل للمراجعة) فالإصدار يبقى، والبناء
    // يرتفع بواحد — ١٥٤ محروقة.
    // **١٥٦**: ١٥٥ رُفعت ثمّ صارت شاشة الدخول مختصرة (أيقونات Apple/Google/موظّف بصفٍّ واحد
    // بلا تمرير على آيفون ١٣) — ١٥٥ محروقة كذلك.
    expect(build, lessThanOrEqualTo(156),
        reason: 'رقم البناء $build فوق السقف — '
            'البناء التجريبيّ لا يرفع الرقم، والسقف يرتفع مع النشر وحده');
    expect(build, greaterThan(155),
        reason: 'رقم البناء $build استُهلك سلفاً — ٣.٠.٠+١٥٥ رُفعت إلى المتجر');

    // الإصدار فوق آخر قطارٍ مُغلق/مرفوع (٢.٢.٨) — مقارنةٌ رقميّة لا نصّيّة.
    final name = major * 1000000 + minor * 1000 + patch;
    const lastSubmitted = 2 * 1000000 + 2 * 1000 + 8; // 2.2.8
    expect(name, greaterThan(lastSubmitted),
        reason: 'الإصدار $major.$minor.$patch لا يتجاوز ٢.٢.٨ — '
            'قطار ٢.٢.٧ مغلق و٢.٢.٨ مرفوع؛ رفع البناء وحده يُرفض');
    expect(major, lessThanOrEqualTo(3),
        reason: 'الإصدار الرئيسيّ $major لا يطابق مسار المتجر (3.x)');
  });
}
