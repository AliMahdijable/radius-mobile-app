import 'package:flutter_test/flutter_test.dart';
import 'package:rad_mysvcs/core/util/phone.dart';

/// حارس الرقم المحلّي.
///
/// 🐛 طلب المستخدم ٢٠٢٦-١٠-٠٥: «يتّصل بس بدون مفتاح الدولة. والنسخ
/// واللصق هم كذلك». والخادم يُطبّع الأرقام دوليّاً (`07x` ← `9647x`)،
/// فالتحويل يقع في التطبيق — وكلّ صفٍّ هنا من جدول القسم ٣ في
/// `docs/subscriber-phone-call-prompt.md`.
void main() {
  group('الصيغ المعروفة', () {
    const cases = {
      '9647827381676': '07827381676',
      '+964 782 738 1676': '07827381676',
      '009647827381676': '07827381676',
      '07827381676': '07827381676',
      '7827381676': '07827381676',
      '964 782 738 1676': '07827381676',
      '+9647827381676': '07827381676',
    };
    cases.forEach((input, want) {
      test('$input ← $want', () => expect(localPhone(input), want));
    });
  });

  group('ما لا يُفهَم يبقى كما وصل', () {
    // ⚠️ التحويل بالقوّة يُنتج رقماً **آخر**، وطالبُ الدعم يتّصل بغريب.
    for (final raw in const ['447911123456', '12345', 'لا رقم', '+1 555 0100']) {
      test('«$raw»', () => expect(localPhone(raw), raw));
    }

    test('🚨 رقمٌ أجنبيٌّ يبدأ صدفةً بـ964 لا يُقَصّ', () {
      // الاشتراط على طول الباقي لا على البادئة وحدها.
      expect(localPhone('96412'), '96412');
      expect(localPhone('9641234567890123'), '9641234567890123');
    });
  });

  group('الحالات الطرفيّة', () {
    test('الفارغ يبقى فارغاً', () {
      expect(localPhone(''), '');
      expect(localPhone('   '), '');
    });

    test('بلا خاناتٍ إطلاقاً', () => expect(localPhone('—'), '—'));

    test('المسافات تُقلَّم', () => expect(localPhone(' 9647827381676 '), '07827381676'));
  });

  group('مفتاح الدولة معاملٌ لا ثابت', () {
    // المنصّة قد تخدم دولاً أخرى، والرقم لا يُكتب مكرّراً في كلّ موضع.
    test('مفتاحٌ آخر يعمل', () {
      expect(localPhone('9627912345678', countryCode: '962'), '07912345678');
    });

    test('ولا يمسّ رقماً من دولةٍ أخرى', () {
      expect(localPhone('9647827381676', countryCode: '962'), '9647827381676');
    });
  });

  group('الواتساب لا يُمسّ', () {
    test('🚨 الدوليّ يبقى دوليّاً لـwa.me', () {
      // `wa.me` يشترط مفتاح الدولة. هذا الحارس يوثّق أنّ `localPhone`
      // **ليست** لمسار الواتساب — فمن يستعملها هناك يكسره.
      const intl = '9647827381676';
      expect(localPhone(intl), isNot(intl));
      expect(intl.replaceAll(RegExp(r'[^0-9]'), ''), intl);
    });
  });
}
