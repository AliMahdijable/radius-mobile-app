import 'package:flutter/foundation.dart';

/// إشارةُ تغيّر الأجهزة — تُطلَق بعد كلّ إضافة/تعديل/حذف جهاز أو تعديل منطقة،
/// فتُحدِّث **فوراً** كلّ الأسطح المفتوحة (القائمة، النظرة العامّة، البرج) بلا
/// إعادة تحميلٍ يدويّ.
///
/// السبب (طلب المالك ٢٧ أكتوبر — «التحديث الفوريّ»): كانت كلّ شاشةٍ تحمل
/// لقطةً مستقلّة من الأجهزة؛ فتعديل اسم جهازٍ في مكانٍ لا ينعكس في البرج أو
/// النظرة العامّة إلّا بإعادة فتحها. الآن عمليّة الحفظ تُطلِق [bump]، وكلّ سطحٍ
/// مفتوحٍ يستمع فيُعيد الجلب لحظتها.
class DeviceEvents {
  DeviceEvents._();

  /// عدّادٌ يتزايد مع كلّ تغيير. الأسطح تستمع إليه عبر [ValueNotifier].
  static final ValueNotifier<int> changes = ValueNotifier<int>(0);

  /// يُعلن أنّ أجهزةً (أو مناطق) تغيّرت.
  static void bump() => changes.value = changes.value + 1;
}
