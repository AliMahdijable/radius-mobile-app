import 'package:flutter/foundation.dart';

/// إشارةٌ تُطلقها اللوحة حين تريد أن **يتحدّث كلّ ما عليها**، بما فيه
/// الودجات التي تملك حالتها وتجلب بياناتها بنفسها.
///
/// ── لماذا وُجدت ────────────────────────────────────────────────
/// `HeroRevenueCard` يملك حالته ويجلب إيراداته وحده، ويستمع إلى
/// `SubscriberEvents.dataChanged` و`AppResumedSignal.tick`. وليس منهما
/// **سحب التحديث**: فكان المدير يسحب، فتتحدّث بقيّة الكارتات ويبقى
/// كارت الإيرادات على «تعذّر الجلب — اسحب للتحديث» مهما سحب. بلاغٌ
/// حقيقيّ (٢٠٢٦-٠٩-١٤).
///
/// والسبب أنّ `onRefresh` في اللوحة ينادي دوالّها هي
/// (`_loadIdentity` · `_refreshLive`)، ولا سبيل له إلى حالة ودجةٍ
/// ابنة.
///
/// ── ولماذا إشارةٌ لا `GlobalKey` ─────────────────────────────────
/// المفتاح يربط الأب بابنٍ **بعينه**، فكلّ ودجةٍ جديدة تملك حالتها
/// تحتاج مفتاحاً وسطراً في الأب. والإشارة تجعل العقد مفتوحاً: من يجلب
/// بنفسه يستمع، والأب لا يعرف كم ابناً يسمعه.
///
/// وهو نفس نمط [AppResumedSignal] المستعمَل في المشروع — لا اختراع.
///
/// ⚠️ **لا تُطلقها من داخل بناء**: قيمتها تتغيّر فتُعيد بناء مستمعيها،
/// وإطلاقها أثناء البناء يرمي. أطلقها من معالج حدثٍ أو `Future`.
class DashboardRefreshSignal {
  DashboardRefreshSignal._();

  static final ValueNotifier<int> tick = ValueNotifier<int>(0);

  static void bump() {
    tick.value = tick.value + 1;
  }
}
