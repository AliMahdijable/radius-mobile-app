/// ما تعرفه «طابعة الوصولات» (بلوتوث / طابعة الجهاز) عن وصلٍ أُرسل إليها.
enum PrintAck {
  /// ليس من الطابعة المباشرة (نافذة الطباعة، الحاسبة) — كما كان.
  none,

  /// وصلت الطابعةَ بايتات الوصل كلّها، وهي لا تخبر هل طبعت (كثيرٌ من طابعات البلوتوث صامتة).
  sent,

  /// الطابعة نفسها قالت إنّها أنهت الوصل (طابعة SUNMI، أو طابعة بلوتوث تجيب أسئلة الحالة).
  confirmed,

  /// الوصل نفسه أُرسل قبل لحظات (نقرٌ مكرّر) — لم يُرسل مرّةً ثانية.
  duplicate,
}

/// لماذا لم يخرج الوصل من طابعة الوصولات — يُعرض سبباً بكلماتٍ يفهمها الوكيل لا رمزاً.
enum PrintIssue {
  /// لم يُسمح للتطبيق بالأجهزة المجاورة (أندرويد ١٢+) — يُسأل ثانيةً.
  permission,

  /// الرفض صار دائماً — يُفتح من إعدادات الهاتف. الآيفون: كلّ رفضٍ دائم (لا يسأل إلّا مرّة).
  permissionBlocked,

  /// الجهاز بلا بلوتوث.
  btUnsupported,

  /// البلوتوث مطفأ.
  btOff,

  /// الطابعة المحفوظة غير مقترنة / غير موجودة.
  notFound,

  /// لم يتمّ الاتصال (مطفأة، بعيدة، أو متّصلة بهاتفٍ آخر).
  connectFailed,

  /// الطابعة لا تردّ.
  timeout,

  /// طابعة BLE بلا قناةٍ تستقبل الطباعة.
  noWriteChannel,

  /// انقطع الاتصال قبل أن يُرسل شيءٌ من الوصل — لم يُطبع شيء.
  disconnected,

  /// انقطع الاتصال **أثناء** الإرسال — غير مؤكَّد: قد يكون خرج جزءٌ من الوصل.
  disconnectedMidway,

  /// الطابعة قالت إنّ الورق نفد — قبل الإرسال، فلم يُرسل شيء.
  paperOut,

  /// نفد الورق أثناء الوصل — غير مؤكَّد.
  paperOutMidway,

  /// غطاء الطابعة مفتوح.
  coverOpen,

  /// رأس الطباعة ساخن.
  overheated,

  /// لا طابعة مدمجة مدعومة في هذا الجهاز (المدعوم الآن: SUNMI).
  builtinMissing,

  /// طابعة الجهاز تبلّغ عطلاً.
  builtinFault,

  /// طابعة الجهاز تتهيّأ.
  builtinBusy,

  /// طابعة الجهاز لم تؤكّد خلال المهلة — غير مؤكَّد.
  builtinUnconfirmed,

  /// طابعة الجهاز قالت إنّها لم تُكمل الوصل — غير مؤكَّد.
  builtinRejected,

  /// تعذّر تحويل الوصل لصورةٍ بعرض الطابعة.
  render,

  /// لم تُختر طابعة بعد.
  notConfigured,

  /// غير ذلك.
  unknown;

  /// هل قد يكون خرج جزءٌ من الوصل؟ ⇒ «غير مؤكَّد» وإعادة طباعةٍ يدويّة.
  bool get uncertain =>
      this == disconnectedMidway || this == paperOutMidway || this == builtinUnconfirmed || this == builtinRejected;
}
