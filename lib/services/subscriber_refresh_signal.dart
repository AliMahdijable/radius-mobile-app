import 'package:flutter/foundation.dart';

/// إشارةٌ تُطلقها شاشة المشترك حين يسحب المدير للتحديث، ليتحدّث معها
/// **كلّ ما على الشاشة** — بما فيه الودجات التي تملك حالتها وتجلب
/// بياناتها بنفسها.
///
/// ── لماذا وُجدت ────────────────────────────────────────────────
/// `DeviceProbeCard` يملك حالته ويفحص جهاز المشترك وحده. و`onRefresh`
/// في الشاشة ينادي دوالّها هي، ولا سبيل له إلى حالة ودجةٍ ابنة —
/// فيسحب المدير فتتحدّث بيانات الاشتراك ويبقى كرت الجهاز على ما كان.
///
/// وهو **نفس العطل** الذي أصاب كارت الإيرادات في اللوحة وأُصلح بـ
/// [DashboardRefreshSignal] (٢٠٢٦-٠٩-١٤) — ونفس العلاج، لا اختراع.
///
/// وأشدّ ما يحتاجها حالتان يتجمّد فيهما الكرت تماماً بلا هذه الإشارة:
/// جهاز ONT (لا نبضة دوريّة له أصلاً)، وجهازٌ تعذّر الوصول إليه —
/// وهو بالضبط ما يسحب المدير ليُعيد المحاولة عليه.
///
/// ── ولماذا إشارةٌ لا `GlobalKey` ─────────────────────────────────
/// المفتاح يربط الأب بابنٍ بعينه، فكلّ ودجةٍ جديدة تجلب بنفسها تحتاج
/// مفتاحاً وسطراً في الأب. والإشارة تجعل العقد مفتوحاً: من يجلب بنفسه
/// يستمع، والأب لا يعرف كم ابناً يسمعه.
///
/// ⚠️ **لا تُطلقها من داخل بناء**: قيمتها تتغيّر فتُعيد بناء مستمعيها،
/// وإطلاقها أثناء البناء يرمي. أطلقها من معالج حدثٍ أو `Future`.
class SubscriberRefreshSignal {
  SubscriberRefreshSignal._();

  static final ValueNotifier<int> tick = ValueNotifier<int>(0);

  static void bump() => tick.value = tick.value + 1;
}
