/// تباطؤ الفحص — ومَن يخضع له ومَن لا يخضع.
///
/// ── ما يحلّه ──────────────────────────────────────────────────────
/// شاشة الأجهزة تمسح كلّ ٢٠ ثانية. وجهازٌ منقطعٌ منذ ساعة لا فائدة من
/// سؤاله ثلاث مرّاتٍ في الدقيقة: مقبسٌ يُفتح ومهلةٌ تُستنفد وبطّاريّةٌ
/// تُستهلك مقابل الجواب نفسه. فيتباطأ سؤالُه كلّما تكرّر إخفاقه، حتّى
/// مرّةٍ كلّ دقيقتين.
///
/// ── 🐛 وأين أخطأ التطبيق ──────────────────────────────────────────
/// بلاغ المستخدم ٢٠٢٦-٠٩-٠٤: «الدخول ع الأجهزة يجلب ٣ ويوقف، أخرج
/// وأرجع للقسم ٣ مرّات حتّى يظهرهم كلّهم».
///
/// كان التباطؤ يُطبَّق على **كلّ** استدعاء بلا تمييز — والاستدعاءات خمسة
/// ومصادرها مختلفة تماماً:
///
/// | المصدر | من طلبه | يخضع للتباطؤ؟ |
/// |---|---|---|
/// | مؤقّت ٢٠ ثانية | لا أحد | **نعم** — هذا سببه |
/// | دخول التبويب | المستخدم | لا |
/// | سحب التحديث | المستخدم | لا |
/// | العودة من الخلفيّة | المستخدم | لا |
/// | أوّل تحميل | المستخدم | لا |
///
/// فمن يفتح الشاشة عمداً ينتظر جواباً عن **كلّ** جهاز الآن، لا عن
/// السدس الذي حان دورُه.
///
/// ── ولماذا كانت «ثلاثة» بالذات ────────────────────────────────────
/// هاتف المدير غالباً على بيانات الجوّال لا على شبكة الأجهزة، فتُخفق
/// أكثرها وتبلغ السقف ٦. وشاشة التبويب داخل `IndexedStack` **لا
/// تُهدَم** — فيبقى عدّاد الجولات وخريطة الإخفاقات حيّين طوال عمر
/// التطبيق، ولا يبدآن من الصفر مع كلّ دخول.
///
/// فكلّ دخولٍ يفحص من تقسم دورتُه رقمَ الجولة: أقلّيّةٌ تتبدّل في كلّ
/// مرّة، وثلاث دخلاتٍ تلزم لتغطية الجميع.
///
/// ⚠️ والفصل هنا في دالّةٍ خالصة لا داخل الشاشة عمداً: المنطق الذي
/// أخفى نفسه في ١٤٧١ سطراً هو الذي لم يُختبَر. `test/probe_backoff_test.dart`
/// يحاكي جولاتٍ متتالية ويقيس التغطية.
library;

/// سقف التباطؤ: مرّة كلّ ٦ جولات = دقيقتان.
const int kMaxBackoffRounds = 6;

/// هل يُفحص جهازٌ إخفاقاتُه المتتالية [consecutiveFailures] في الجولة
/// رقم [round]؟
///
/// [force] = طلبٌ من المستخدم: يتخطّى التباطؤ كلّه ويُرجع `true` دائماً.
bool deviceProbeDue({
  required bool force,
  required int consecutiveFailures,
  required int round,
}) {
  if (force) return true;
  if (consecutiveFailures <= 0) return true;
  final skipEvery = consecutiveFailures.clamp(1, kMaxBackoffRounds);
  return round % skipEvery == 0;
}
