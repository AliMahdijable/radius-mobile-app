/// عزل ثنائيّ الاتّجاه.
///
/// ── العطل ─────────────────────────────────────────────────────────
/// القيمة التي تخلط لاتينيّاً بعربيّ داخل فقرةٍ عربيّة يُفكّكها محرّك
/// الاتّجاه الثنائيّ (Unicode BiDi) ويُعيد ترتيب أجزائها. ما رآه
/// المستخدم في ٢٠٢٦-٠٩-٠١:
///
/// | كُتب                  | ظهر                   |
/// |-----------------------|------------------------|
/// | `86/78 Mbps · 10 يوماً` | `86/78 10 Mbps · يوماً` |
/// | `6.49.19 (long-term)`  | `(long-term) 6.49.19`  |
/// | `23.1 V`               | `V 23.1`               |
///
/// السبب أنّ الأرقام والرموز محايدةٌ اتّجاهيّاً، فتلتصق بالجار القويّ
/// الخطأ. والكلمة العربيّة في آخر السطر تسحب ما قبلها.
///
/// ── العلاج ───────────────────────────────────────────────────────
/// FSI (First Strong Isolate) يعزل المقطع ويستنتج اتّجاهه من **أوّل
/// حرفٍ قويّ** فيه، ثمّ PDI يُغلق العزل. فيبقى المقطع وحدةً واحدة مهما
/// جاوره:
///
/// - `23.1 V` → أوّل قويّ `V` → لاتينيّ → `23.1 V` ✓
/// - `10 يوماً` → أوّل قويّ `ي` → عربيّ → `10 يوماً` ✓
///
/// ⚠️ لا تستعمل `Directionality` لهذا: هي تفرض اتّجاهاً واحداً على كلّ
/// ما بداخلها، فتُصلح نصف القيم وتكسر نصفها. FSI يستنتج لكلّ مقطع.
library;

/// حرف بدء العزل ذي الاتّجاه المُستنتَج (U+2068).
///
/// بالهروب لا حرفيّاً: الحرف الحرفيّ يقلب مظهر الشيفرة في المحرّر عمّا
/// يقرؤه المصرّف، والمحلّل يرفضه لهذا السبب.
const _fsi = '\u2068';

/// حرف إنهاء العزل (U+2069).
const _pdi = '\u2069';

/// يعزل [s] فلا يتفكّك بين جيرانه.
///
/// آمنٌ على النصّ العربيّ الخالص واللاتينيّ الخالص — لا يُغيّرهما.
/// والفارغ يبقى فارغاً لئلّا نُدخل حرفَي تحكّمٍ بلا محتوى.
String iso(String s) => s.isEmpty ? s : '$_fsi$s$_pdi';

/// يعزل كلّ مقطع ثمّ يصل — لا يكفي عزل الناتج مجتمعاً.
///
/// `iso('a · b')` يجعل الاثنين وحدةً واحدة باتّجاه أوّلها، فيُقلب
/// المقطع الثاني. العزل يجب أن يكون **لكلّ مقطع على حدة**.
String isoJoin(Iterable<String> parts, String sep) =>
    parts.where((p) => p.isNotEmpty).map(iso).join(sep);
