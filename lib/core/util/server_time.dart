/// قراءة التوقيتات القادمة من الخادم — **واصطلاحان لا واحد**.
///
/// ── العطل الذي تُصلحه ─────────────────────────────────────────────
/// 🐛 بلاغ المستخدم ٢٠٢٦-٠٩-٠٤: «تسديد دين منذ: يقرأ ٣ ساعات حتّى لو
/// هسّة سدّدته». وثلاث ساعات هي فرق بغداد عن UTC بالضبط.
///
/// ⚠️ **تصويبٌ لتشخيصٍ أوّليّ خاطئ منّي** (يبقى مكتوباً لأنّ الخطأ نفسه
/// مُغرٍ): ظننتُ الخلفيّة ترسل نصّاً عارياً بلا منطقة. **وهي لا ترسله.**
/// قِيس: `mysql2` مضبوطٌ بـ`dateStrings: false` فيُرجع كائن `Date`،
/// و`JSON.stringify` يُسلسله ISO **موسوماً بـZ**:
///
///     {"created_at":"2026-09-04T12:35:54.000Z"}
///
/// ولا `DATE_FORMAT` واحدة في المشروع كلّه — فكلّ توقيتات جداولنا تصل
/// موسومة.
///
/// ── فأين كان العطل إذن؟ ──────────────────────────────────────────
/// في **الكود نفسه**، بنمطين اثنين لا ثالث لهما:
///
/// ١. **حذفُ الوسم بيدنا**. كان `subscriber_card_v3` يكتب
///    `raw.split('.').first.replaceAll('T', ' ')` لتنظيف الكسور —
///    فيُسقط الـ`Z` معها:
///
///        "2026-09-04T12:35:54.000Z"  →  "2026-09-04 12:35:54"
///
///    والعاري يُقرأ محلّيّاً، فيصير الفرق ثلاث ساعات. **هذا هو بالضبط
///    ما رآه المستخدم.**
///
/// ٢. **قراءة `.hour` من قيمةٍ عالميّة بلا `toLocal()`**. القيمة صحيحة
///    والعرض خاطئ: ١٢ بدل ١٥. وهذا ما كان في سجلّ الحركات.
///
/// ⚠️ وما ليس عطلاً: `difference` صحيحةٌ دائماً (تقارن لحظاتٍ مطلقة
/// بلا نظرٍ إلى `isUtc`)، و`.toLocal()` على نصٍّ موسوم **تعمل فعلاً**.
/// قلتُ أوّلاً إنّها «بلا أثر» — وكان ذلك خطأً بُني على الافتراض الخاطئ
/// أعلاه.
///
/// ── والاصطلاحان اللذان يبقيان ────────────────────────────────────
/// | المصدر | الشكل | القراءة |
/// |---|---|---|
/// | جداولنا | `…T12:35:54.000Z` | موسوم — يكفيه `toLocal()` |
/// | الساس | `2026-10-04 20:00:00` | عارٍ **وبتوقيت بغداد** |
///
/// (دليل الثاني: `templateHelper.js:284` يُلحق `+03:00` بتواريخ الساس
/// صراحةً في الخلفيّة.)
///
/// فـ[parseServerUtc] تحتمل الشكلين: تسم العاري وتحترم الموسوم، ثمّ
/// تُحوّل. و[parseSasLocal] تُبقي تواريخ الساس محلّيّةً كما هي.
///
/// ⚠️ والقيمة الحقيقيّة للوحدة ليست إصلاح عطلٍ واحد، بل أن يصير
/// الاصطلاح **مذكوراً في موضع الاستدعاء**: `parseServerUtc` أو
/// `parseSasLocal` — فلا يبقى الفرق بينهما معرفةً في رأس أحد.
library;

/// هل يحمل النصّ منطقةً زمنيّة صريحة؟ (`Z` أو `+03:00` أو `-05:00`)
final _hasZone = RegExp(r'(Z|[+-]\d{2}:?\d{2})$');

/// يقرأ توقيتاً **من قاعدتنا** ويُرجعه بتوقيت الجهاز.
///
/// يقبل `2026-09-04 11:39:56` و`2026-09-04T11:39:56` و
/// `2026-09-04T11:39:56.123Z` — بمسافةٍ أو بحرف T، وبكسورٍ أو بدونها.
///
/// ⚠️ **لا تستعملها لتواريخ الساس** (`expiration` · `last_online`) —
/// تلك بتوقيت بغداد أصلاً، ووسمُها `Z` يُقدّمها ثلاث ساعات.
/// استعمل [parseSasLocal] لها.
DateTime? parseServerUtc(String? raw) {
  final s = raw?.trim();
  if (s == null || s.isEmpty) return null;

  // الصيغة الوحيدة التي يفهمها `DateTime.parse` هي ISO — والخلفيّة
  // ترسل أحياناً بمسافةٍ بدل T (كما يخرج من MySQL مباشرةً).
  var iso = s.replaceFirst(' ', 'T');
  if (!_hasZone.hasMatch(iso)) iso = '${iso}Z';

  final dt = DateTime.tryParse(iso);
  return dt?.toLocal();
}

/// يقرأ تاريخاً **من الساس** — وهو بتوقيت بغداد.
///
/// يُترك كما هو عمداً: الأجهزة في العراق، فقراءتُه محلّيّاً صحيحة.
/// ووجودُ الدالّة يجعل النيّة صريحةً في موضع الاستدعاء بدل أن تكون
/// غياباً يُفسَّر سهواً لاحقاً.
DateTime? parseSasLocal(String? raw) {
  final s = raw?.trim();
  if (s == null || s.isEmpty) return null;
  return DateTime.tryParse(s.replaceFirst(' ', 'T'));
}

/// «منذ كذا» بالعربيّة — للتوقيتات القادمة من قاعدتنا.
///
/// ⚠️ يُرجع «الآن» لكلّ ما دون الدقيقة، ولا يُرجع سالباً أبداً: توقيتٌ
/// في المستقبل بثوانٍ (فارق ساعةٍ بين الخادم والجهاز) يجب أن يُقرأ
/// «الآن» لا «منذ −١ دقيقة».
String timeAgoAr(DateTime? at, {DateTime? now}) {
  if (at == null) return '';
  final n = now ?? DateTime.now();
  final d = n.difference(at);
  if (d.isNegative || d.inMinutes < 1) return 'الآن';
  if (d.inMinutes < 60) return 'منذ ${d.inMinutes} دقيقة';
  if (d.inHours < 24) return 'منذ ${d.inHours} ساعة';
  if (d.inDays < 30) return 'منذ ${d.inDays} يوم';
  final months = d.inDays ~/ 30;
  if (months < 12) return 'منذ $months شهر';
  return 'منذ ${d.inDays ~/ 365} سنة';
}
