/// الرقم المحلّي للاتصال والنسخ.
///
/// 🐛 طلب المستخدم ٢٠٢٦-١٠-٠٥ (`docs/subscriber-phone-call-prompt.md`):
/// «هذا الزرّ مفروض يتفعّل الاتصال كما معروف بالعراق: يتّصل بس بدون
/// مفتاح الدولة. والنسخ واللصق هم كذلك».
///
/// الخادم يُطبّع أرقام المشتركين إلى الصيغة الدوليّة (`07x` ← `9647x`)،
/// فما يصل التطبيق `9647XXXXXXXXX` غالباً. وهي صيغةٌ صحيحةٌ للواتساب
/// ومربكةٌ للاتصال والنسخ: المشغّل يريد `07827381676` كما يكتبه ويقرؤه.
///
/// ⚠️ **لا تُستعمل مع الواتساب.** `wa.me` يشترط مفتاح الدولة، فتحويله
/// محلّيّاً يفتح محادثةً لرقمٍ آخر أو لا يفتح شيئاً.
library;

/// يُحوّل [raw] إلى الصيغة المحلّيّة، أو يُعيده كما وصل إن لم يُفهَم.
///
/// [countryCode] معامل لا ثابت: المنصّة قد تخدم دولاً أخرى، والرقم
/// لا يُكتب مكرّراً في كلّ موضع استعمال.
///
/// | المدخل | المخرج |
/// |---|---|
/// | `9647827381676` | `07827381676` |
/// | `+964 782 738 1676` | `07827381676` |
/// | `009647827381676` | `07827381676` |
/// | `07827381676` | كما هو |
/// | `7827381676` | `07827381676` |
/// | `447911123456` | **كما وصل** |
///
/// ⚠️ **ما لا يُفهَم يُعاد كما وصل، ولا تُخترَع له صيغة.** رقمٌ أجنبيٌّ
/// حُوِّل بالقوّة يصير رقماً آخر — وطالبُ الدعم يتّصل بغريب.
String localPhone(String raw, {String countryCode = '964'}) {
  final trimmed = raw.trim();
  if (trimmed.isEmpty) return trimmed;

  // الخانات وحدها: المسافات والشرطات والأقواس و`+` زينةُ عرضٍ لا هويّة.
  var d = trimmed.replaceAll(RegExp(r'[^0-9]'), '');
  if (d.isEmpty) return trimmed;

  // بادئة الخروج الدوليّة قبل مفتاح الدولة، لا بعده.
  if (d.startsWith('00$countryCode')) {
    d = d.substring(2);
  }
  if (d.startsWith(countryCode)) {
    final rest = d.substring(countryCode.length);
    // ⚠️ الاشتراط على الباقي لا على البادئة وحدها: رقمٌ أجنبيٌّ قد
    // يبدأ صدفةً بالمفتاح نفسه، وقصُّه منه يُنتج رقماً لا وجود له.
    if (rest.length >= 9 && rest.length <= 10) {
      return rest.startsWith('0') ? rest : '0$rest';
    }
    return trimmed;
  }

  if (d.startsWith('0')) return d;

  // عشر خاناتٍ بلا صفرٍ ولا مفتاح — صيغةٌ شائعةٌ في الإدخال اليدويّ.
  if (d.length == 10) return '0$d';

  return trimmed;
}
